const assert=require('node:assert/strict');
const fs=require('node:fs');
const guide=require('../guide-model.js');
const tools=require('../isc-tools.js');
const catalogue=JSON.parse(fs.readFileSync('data/catalogue.json','utf8'));
const facts=JSON.parse(fs.readFileSync('data/visuals.json','utf8'));
const survey=JSON.parse(fs.readFileSync('data/survey-summary.json','utf8'));
const branches=JSON.parse(fs.readFileSync('data/branch-summary.json','utf8'));
const ids=new Set(catalogue.files.map(x=>x.id));
for(const topic of guide.topics)for(const group of guide.groups)for(const file of guide.recordsFor(topic.id,group.id))assert(ids.has(file.id),`Missing guide source ${file.id}`);
for(const value of ['',null,undefined,'X',9999])assert.equal(guide.published(value),null);
assert.equal(guide.published('0'),0);assert.equal(guide.published('99'),99);
assert.equal(guide.surveyRows(facts,survey,'harassment','black')[2].value,null);
assert.equal(guide.surveyRows(facts,survey,'harassment','black')[1].value,15);
assert.equal(tools.difference(8.9,12),-3.1);assert.equal(tools.difference(21,22.9),-1.9);assert.equal(tools.difference(12,12),0);
for(const input of ['',null,undefined,-1,101,NaN])assert.equal(tools.difference(input,12),null);
assert.equal(tools.requestText(),null);
const text=tools.requestText({language:'fr',recipient:'Équipe du SAC',items:['Embauche'],purpose:'Comparer les résultats'});
assert(text.includes('Embauche')&&text.includes('Comparer les résultats')&&text.includes('Destinataire : Équipe du SAC'));
assert(!text.includes('undefined'));
assert.equal(tools.cellValue(0,'en'),'0%');assert.equal(tools.cellValue(9999,'en'),'Unavailable');assert.equal(tools.cellValue('X','fr'),'Supprimé (X)');
const rows=tools.branchRows(branches,{question:'Q42',group:'5',view:'branches'});
assert.equal(rows.length,11);assert.equal(rows.find(x=>x.en.startsWith('FNIH-')).value,44);
assert.equal(tools.branchRows(branches,{question:'Q72',branch:'205',view:'groups'}).length,18);
for(const file of ['app.js','guide-model.js','explore.js','isc-tools.js'])require('node:child_process').execFileSync('node',['--check',file]);
console.log('PASS: guide paths, genuine zeroes, suppression, branch comparisons, request drafts and percentage-point arithmetic.');
